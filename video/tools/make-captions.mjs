// Writes compositions/captions.html from the clock: one caption per narration line, on screen from the line's start to
// the end of its recording (assets/voice/<id>.wav) plus 0.5 s, never past the next line. Run after audio/voice.mjs.
// Usage: node tools/make-captions.mjs
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
await import("../assets/js/clock.js");
const C = globalThis.CLOCK;
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;");
const rows = C.lines.map(([id, at, caption], i) => {
  const said = Number(execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", join(ROOT, "assets/voice", `${id}.wav`)]).toString());
  const end = Math.min(at + C.windowOf(i), at + said + 0.5);
  const slug = id.replace(".", "-");
  return `        <p id="cap-${slug}" class="clip cap" data-start="${at.toFixed(2)}" data-duration="${(end - at).toFixed(2)}" data-track-index="0">${esc(caption)}</p>`;
});
writeFileSync(
  join(ROOT, "compositions/captions.html"),
  `<!doctype html>
<html>
  <head>
    <meta charset="UTF-8" />
  </head>
  <body>
    <!-- Generated by tools/make-captions.mjs from assets/js/clock.js and the recorded lines. Never edit by hand. -->
    <template>
      <style>
        #root {
          position: absolute;
          inset: 0;
        }
        .cap {
          position: absolute;
          left: 830px;
          top: 906px;
          width: 980px;
          font-family: var(--f-body);
          font-weight: 700;
          font-size: 30px;
          line-height: 1.3;
          color: var(--ink);
        }
      </style>
      <div id="root" data-composition-id="captions" data-width="1920" data-height="1080">
${rows.join("\n")}
      </div>
      <script>
        (function () {
          const tl = gsap.timeline({ paused: true });
          tl.set({}, {}, CLOCK.duration);
          window.__timelines["captions"] = tl;
        })();
      </script>
    </template>
  </body>
</html>
`,
);
console.log(`compositions/captions.html: ${rows.length} captions`);
